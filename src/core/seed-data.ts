export function assignJournalistForArticle(
  categorySlug: ArticleRecord['categorySlug'],
  headline: string
): { authorId: string; authorName: string; authorRole: string } {
  let hash = 0;
  for (let i = 0; i < headline.length; i++) {
    hash = (hash * 31 + headline.charCodeAt(i)) >>> 0;
  }

  const isSyria =
    categorySlug === 'syria' ||
    /(سوريا|سوري|دمشق|حلب|حماة|حمص|اللاذقية|طرطوس|درعا|دير الزور|إدلب|السويداء|الحسكة|الرقة|سانا|نصيب|باب الهوى)/.test(
      headline
    );
  if (isSyria) {
    const idx = hash % SYRIA_50_SPECS.length;
    const spec = SYRIA_50_SPECS[idx];
    return {
      authorId: `jour-syria-${idx + 1}`,
      authorName: spec.name,
      authorRole: spec.desk,
    };
  }

  const isArabOrTurkey =
    categorySlug === 'arab-world' ||
    /(تركيا|تركي|أنقرة|إسطنبول|العربي|عربية|الخليج|السعودية|قطر|الإمارات|مصر|الأردن|العراق|لبنان|فلسطين|غزة|الكويت|عُمان|تونس|الجزائر|المغرب|السودان|ليبيا|اليمن)/.test(
      headline
    );
  if (isArabOrTurkey) {
    const idx = hash % ARAB_TURKEY_40_SPECS.length;
    const spec = ARAB_TURKEY_40_SPECS[idx];
    return {
      authorId: `jour-arab-tr-${idx + 1}`,
      authorName: spec.name,
      authorRole: spec.desk,
    };
  }

  const idx = hash % OTHER_10_SPECS.length;
  const spec = OTHER_10_SPECS[idx];
  return {
    authorId: `jour-other-${idx + 1}`,
    authorName: spec.name,
    authorRole: spec.desk,
  };
}

